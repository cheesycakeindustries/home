final class ClipCellView: NSTableCellView {
    private let indexLabel = NSTextField(labelWithString: "")
    private let thumb = NSImageView()
    private let titleLabel = NSTextField(labelWithString: "")
    private let dateLabel = NSTextField(labelWithString: "")

    static let dateFormatter: RelativeDateTimeFormatter = {
        let f = RelativeDateTimeFormatter()
        f.unitsStyle = .short
        f.locale = Locale(identifier: "de_DE")
        return f
    }()

    init() {
        super.init(frame: .zero)
        indexLabel.font = .monospacedDigitSystemFont(ofSize: 11, weight: .medium)
        indexLabel.textColor = .secondaryLabelColor
        indexLabel.alignment = .right

        titleLabel.lineBreakMode = .byTruncatingTail
        titleLabel.maximumNumberOfLines = 1
        titleLabel.setContentCompressionResistancePriority(.defaultLow, for: .horizontal)
        titleLabel.setContentHuggingPriority(.defaultLow, for: .horizontal)

        dateLabel.font = .systemFont(ofSize: 11)
        dateLabel.textColor = .tertiaryLabelColor
        dateLabel.setContentCompressionResistancePriority(.required, for: .horizontal)

        thumb.imageScaling = .scaleProportionallyUpOrDown

        let stack = NSStackView(views: [indexLabel, thumb, titleLabel, dateLabel])
        stack.orientation = .horizontal
        stack.spacing = 8
        stack.alignment = .centerY
        stack.translatesAutoresizingMaskIntoConstraints = false
        addSubview(stack)

        NSLayoutConstraint.activate([
            indexLabel.widthAnchor.constraint(equalToConstant: 28),
            thumb.widthAnchor.constraint(equalToConstant: 26),
            thumb.heightAnchor.constraint(equalToConstant: 26),
            stack.leadingAnchor.constraint(equalTo: leadingAnchor, constant: 2),
            stack.trailingAnchor.constraint(equalTo: trailingAnchor, constant: -8),
            stack.centerYAnchor.constraint(equalTo: centerYAnchor),
        ])
        textField = titleLabel
    }

    required init?(coder: NSCoder) { fatalError("not supported") }

    func configure(item: ClipItem, index: Int) {
        indexLabel.stringValue = index < 9 ? "⌘\(index + 1)" : ""
        titleLabel.stringValue = item.title
        dateLabel.stringValue = Self.dateFormatter.localizedString(for: item.date, relativeTo: Date())
        if item.kind == .image, let d = item.imageData {
            thumb.image = NSImage(data: d)
            thumb.isHidden = false
        } else {
            thumb.image = nil
            thumb.isHidden = true
        }
    }
}

final class PickerController: NSObject, NSTableViewDataSource, NSTableViewDelegate, NSSearchFieldDelegate, NSWindowDelegate {
    private let store: ClipStore
    private let panel: KeyPanel
    private let searchField = NSSearchField()
    private let tableView = NSTableView()
    private var filtered: [ClipItem] = []
    private var keyMonitor: Any?
    private var previousApp: NSRunningApplication?

    var onPick: ((ClipItem, NSRunningApplication?) -> Void)?
    var isVisible: Bool { panel.isVisible }

    init(store: ClipStore) {
        self.store = store
        panel = KeyPanel(contentRect: NSRect(x: 0, y: 0, width: 560, height: 460),
                         styleMask: [.titled, .fullSizeContentView, .nonactivatingPanel],
                         backing: .buffered, defer: false)
        super.init()

        panel.titleVisibility = .hidden
        panel.titlebarAppearsTransparent = true
        panel.standardWindowButton(.closeButton)?.isHidden = true
        panel.standardWindowButton(.miniaturizeButton)?.isHidden = true
        panel.standardWindowButton(.zoomButton)?.isHidden = true
        panel.isFloatingPanel = true
        panel.level = .floating
        panel.hidesOnDeactivate = false
        panel.isReleasedWhenClosed = false
        panel.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
        panel.isMovableByWindowBackground = true
        panel.delegate = self

        let effect = NSVisualEffectView()
        effect.material = .popover
        effect.blendingMode = .behindWindow
        effect.state = .active
        panel.contentView = effect

        searchField.placeholderString = "Verlauf durchsuchen …"
        searchField.delegate = self
        searchField.translatesAutoresizingMaskIntoConstraints = false

        let column = NSTableColumn(identifier: NSUserInterfaceItemIdentifier("main"))
        column.resizingMask = .autoresizingMask
        tableView.addTableColumn(column)
        tableView.headerView = nil
        tableView.rowHeight = 34
        tableView.backgroundColor = .clear
        tableView.style = .inset
        tableView.columnAutoresizingStyle = .uniformColumnAutoresizingStyle
        tableView.dataSource = self
        tableView.delegate = self
        tableView.target = self
        tableView.doubleAction = #selector(tableDoubleClicked)

        let scroll = NSScrollView()
        scroll.documentView = tableView
        scroll.hasVerticalScroller = true
        scroll.drawsBackground = false
        scroll.translatesAutoresizingMaskIntoConstraints = false

        let hint = NSTextField(labelWithString: "↑↓ wählen  ·  ⏎ einfügen  ·  ⌘1–9 direkt  ·  ⌘⌫ entfernen  ·  esc schließen")
        hint.font = .systemFont(ofSize: 11)
        hint.textColor = .secondaryLabelColor
        hint.translatesAutoresizingMaskIntoConstraints = false

        effect.addSubview(searchField)
        effect.addSubview(scroll)
        effect.addSubview(hint)

        NSLayoutConstraint.activate([
            searchField.topAnchor.constraint(equalTo: effect.topAnchor, constant: 30),
            searchField.leadingAnchor.constraint(equalTo: effect.leadingAnchor, constant: 14),
            searchField.trailingAnchor.constraint(equalTo: effect.trailingAnchor, constant: -14),
            scroll.topAnchor.constraint(equalTo: searchField.bottomAnchor, constant: 8),
            scroll.leadingAnchor.constraint(equalTo: effect.leadingAnchor, constant: 4),
            scroll.trailingAnchor.constraint(equalTo: effect.trailingAnchor, constant: -4),
            scroll.bottomAnchor.constraint(equalTo: hint.topAnchor, constant: -6),
            hint.leadingAnchor.constraint(equalTo: effect.leadingAnchor, constant: 16),
            hint.bottomAnchor.constraint(equalTo: effect.bottomAnchor, constant: -10),
        ])
    }

    // Anzeigen / Verstecken

    func show() {
        previousApp = NSWorkspace.shared.frontmostApplication
        searchField.stringValue = ""
        refilter()

        let mouse = NSEvent.mouseLocation
        let screen = NSScreen.screens.first { NSMouseInRect(mouse, $0.frame, false) } ?? NSScreen.main
        if let vf = screen?.visibleFrame {
            let size = panel.frame.size
            panel.setFrameOrigin(NSPoint(x: vf.midX - size.width / 2,
                                         y: vf.midY - size.height / 2 + vf.height * 0.1))
        }
        panel.makeKeyAndOrderFront(nil)
        panel.makeFirstResponder(searchField)
        installKeyMonitor()
    }

    func hide() {
        removeKeyMonitor()
        panel.orderOut(nil)
    }

    func windowDidResignKey(_ notification: Notification) { hide() }

    // Tastatur

    private func installKeyMonitor() {
        removeKeyMonitor()
        keyMonitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] event in
            guard let self = self, self.panel.isKeyWindow else { return event }
            let cmd = event.modifierFlags.contains(.command)
            switch Int(event.keyCode) {
            case kVK_Escape:
                self.hide(); return nil
            case kVK_Return, kVK_ANSI_KeypadEnter:
                self.pick(row: self.tableView.selectedRow); return nil
            case kVK_DownArrow:
                self.moveSelection(by: 1); return nil
            case kVK_UpArrow:
                self.moveSelection(by: -1); return nil
            case kVK_Delete where cmd:
                self.deleteSelected(); return nil
            default:
                if cmd, let c = event.charactersIgnoringModifiers, let n = Int(c), (1...9).contains(n) {
                    self.pick(row: n - 1); return nil
                }
                return event
            }
        }
    }

    private func removeKeyMonitor() {
        if let m = keyMonitor { NSEvent.removeMonitor(m) }
        keyMonitor = nil
    }

    private func moveSelection(by delta: Int) {
        guard !filtered.isEmpty else { return }
        let current = tableView.selectedRow
        let next = max(0, min(filtered.count - 1, current + delta))
        tableView.selectRowIndexes(IndexSet(integer: next), byExtendingSelection: false)
        tableView.scrollRowToVisible(next)
    }

    private func deleteSelected() {
        let row = tableView.selectedRow
        guard filtered.indices.contains(row) else { return }
        store.remove(filtered[row])
        refilter(selecting: row)
    }

    @objc private func tableDoubleClicked() {
        pick(row: tableView.clickedRow)
    }

    private func pick(row: Int) {
        guard filtered.indices.contains(row) else { return }
        let item = filtered[row]
        let prev = previousApp
        hide()
        onPick?(item, prev)
    }

    // Suche

    func controlTextDidChange(_ obj: Notification) { refilter() }

    private func refilter(selecting row: Int = 0) {
        let q = searchField.stringValue.trimmingCharacters(in: .whitespaces)
        filtered = q.isEmpty ? store.items : store.items.filter { $0.searchText.localizedCaseInsensitiveContains(q) }
        tableView.reloadData()
        if !filtered.isEmpty {
            let r = min(row, filtered.count - 1)
            tableView.selectRowIndexes(IndexSet(integer: r), byExtendingSelection: false)
            tableView.scrollRowToVisible(r)
        }
    }

    // Tabelle

    func numberOfRows(in tableView: NSTableView) -> Int { filtered.count }

    func tableView(_ tableView: NSTableView, viewFor tableColumn: NSTableColumn?, row: Int) -> NSView? {
        let cell = ClipCellView()
        cell.configure(item: filtered[row], index: row)
        return cell
    }
}

// MARK: - App

final class AppDelegate: NSObject, NSApplicationDelegate, NSMenuDelegate {
    private let store = ClipStore()
    private var picker: PickerController!
    private var hotKey: HotKey?
    private var statusItem: NSStatusItem!

    private var autoPaste: Bool {
        get { UserDefaults.standard.object(forKey: "autoPaste") as? Bool ?? true }
        set { UserDefaults.standard.set(newValue, forKey: "autoPaste") }
    }

    func applicationDidFinishLaunching(_ notification: Notification) {
        picker = PickerController(store: store)
        picker.onPick = { [weak self] item, app in self?.paste(item, into: app) }
        store.start()

        hotKey = HotKey(keyCode: UInt32(kVK_ANSI_V), modifiers: UInt32(cmdKey | shiftKey)) { [weak self] in
            self?.togglePicker()
        }
        if hotKey?.registered != true {
            showAlert("⇧⌘V ist bereits belegt",
                      "Eine andere App (z. B. ein anderer Clipboard-Manager) nutzt das Tastenkürzel schon. Den Verlauf erreichst du trotzdem über das Symbol in der Menüleiste.")
        }

        setupStatusItem()

        if autoPaste && !Paster.isTrusted(prompt: false) {
            _ = Paster.isTrusted(prompt: true)
        }
    }

    @objc private func togglePicker() {
        if picker.isVisible { picker.hide() } else { picker.show() }
    }

    private func paste(_ item: ClipItem, into app: NSRunningApplication?) {
        store.write(item)
        guard autoPaste else { return }
        guard Paster.isTrusted(prompt: false) else {
            _ = Paster.isTrusted(prompt: true)
            return
        }
        if let app = app, app.processIdentifier != ProcessInfo.processInfo.processIdentifier {
            app.activate(options: [])
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) { Paster.sendCmdV() }
    }

    // Menüleiste

    private func setupStatusItem() {
        statusItem = NSStatusBar.system.statusItem(withLength: NSStatusItem.variableLength)
        if let button = statusItem.button {
            let image = NSImage(systemSymbolName: "doc.on.clipboard", accessibilityDescription: "ClipStack")
            image?.isTemplate = true
            button.image = image
        }
        let menu = NSMenu()
        menu.delegate = self
        statusItem.menu = menu
    }

    func menuNeedsUpdate(_ menu: NSMenu) {
        menu.removeAllItems()

        if store.items.isEmpty {
            let empty = NSMenuItem(title: "Noch nichts kopiert", action: nil, keyEquivalent: "")
            empty.isEnabled = false
            menu.addItem(empty)
        } else {
            for (i, item) in store.items.prefix(10).enumerated() {
                var title = item.title
                if title.count > 60 { title = String(title.prefix(60)) + "…" }
                let mi = NSMenuItem(title: title, action: #selector(menuPick(_:)), keyEquivalent: "")
                mi.target = self
                mi.tag = i
                menu.addItem(mi)
            }
        }

        menu.addItem(.separator())

        let open = NSMenuItem(title: "Verlauf öffnen", action: #selector(togglePicker), keyEquivalent: "v")
        open.keyEquivalentModifierMask = [.command, .shift]
        open.target = self
        menu.addItem(open)

        let auto = NSMenuItem(title: "Automatisch einfügen", action: #selector(toggleAutoPaste), keyEquivalent: "")
        auto.target = self
        auto.state = autoPaste ? .on : .off
        menu.addItem(auto)

        if #available(macOS 13.0, *) {
            let login = NSMenuItem(title: "Beim Anmelden starten", action: #selector(toggleLaunchAtLogin), keyEquivalent: "")
            login.target = self
            login.state = SMAppService.mainApp.status == .enabled ? .on : .off
            menu.addItem(login)
        }

        let clear = NSMenuItem(title: "Verlauf leeren …", action: #selector(clearHistory), keyEquivalent: "")
        clear.target = self
        menu.addItem(clear)

        menu.addItem(.separator())
        let quit = NSMenuItem(title: "ClipStack beenden", action: #selector(NSApplication.terminate(_:)), keyEquivalent: "q")
        menu.addItem(quit)
    }

    @objc private func menuPick(_ sender: NSMenuItem) {
        guard store.items.indices.contains(sender.tag) else { return }
        paste(store.items[sender.tag], into: NSWorkspace.shared.frontmostApplication)
    }

    @objc private func toggleAutoPaste() {
        autoPaste.toggle()
        if autoPaste && !Paster.isTrusted(prompt: false) { _ = Paster.isTrusted(prompt: true) }
    }

    @objc private func toggleLaunchAtLogin() {
        guard #available(macOS 13.0, *) else { return }
        do {
            if SMAppService.mainApp.status == .enabled {
                try SMAppService.mainApp.unregister()
            } else {
                try SMAppService.mainApp.register()
            }
        } catch {
            showAlert("Autostart konnte nicht geändert werden", error.localizedDescription)
        }
    }

    @objc private func clearHistory() {
        NSApp.activate(ignoringOtherApps: true)
        let alert = NSAlert()
        alert.messageText = "Gesamten Verlauf leeren?"
        alert.informativeText = "Alle \(store.items.count) gespeicherten Einträge werden entfernt. Die aktuelle Zwischenablage bleibt erhalten."
        alert.addButton(withTitle: "Leeren")
        alert.addButton(withTitle: "Abbrechen")
        if alert.runModal() == .alertFirstButtonReturn { store.clear() }
    }

    private func showAlert(_ title: String, _ text: String) {
        NSApp.activate(ignoringOtherApps: true)
        let alert = NSAlert()
        alert.messageText = title
        alert.informativeText = text
        alert.runModal()
    }
}

let app = NSApplication.shared
let delegate = AppDelegate()
app.delegate = delegate
app.setActivationPolicy(.accessory)
app.run()

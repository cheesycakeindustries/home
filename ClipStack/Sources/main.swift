// ClipStack – erweiterte Zwischenablage für macOS
//
// ⌘C  kopiert wie gewohnt – jede Kopie landet zusätzlich im Verlauf
// ⌘V  fügt wie gewohnt das zuletzt Kopierte ein
// ⇧⌘V öffnet den Verlauf; Auswahl mit ↑↓ und ⏎ (oder ⌘1–9) fügt den Eintrag ein

import Cocoa
import Carbon.HIToolbox
import ServiceManagement

// MARK: - Datenmodell

struct ClipItem: Codable {
    enum Kind: String, Codable { case text, image, files }

    var kind: Kind
    var text: String?
    var rtf: Data?
    var imageData: Data?      // PNG
    var filePaths: [String]?
    var date: Date

    func sameContent(as other: ClipItem) -> Bool {
        guard kind == other.kind else { return false }
        switch kind {
        case .text:  return text == other.text
        case .image: return imageData == other.imageData
        case .files: return filePaths == other.filePaths
        }
    }

    var title: String {
        switch kind {
        case .text:
            let lines = (text ?? "")
                .split(whereSeparator: \.isNewline)
                .map { $0.trimmingCharacters(in: .whitespaces) }
                .filter { !$0.isEmpty }
            var t = lines.first ?? ""
            if t.count > 200 { t = String(t.prefix(200)) + "…" }
            if lines.count > 1 { t += "   (+\(lines.count - 1) Zeilen)" }
            return t
        case .image:
            if let d = imageData, let rep = NSBitmapImageRep(data: d) {
                return "Bild \(rep.pixelsWide) × \(rep.pixelsHigh)"
            }
            return "Bild"
        case .files:
            let names = (filePaths ?? []).map { ($0 as NSString).lastPathComponent }
            if names.count == 1 { return "📄 " + names[0] }
            return "📄 \(names.count) Dateien: " + names.joined(separator: ", ")
        }
    }

    var searchText: String { kind == .text ? (text ?? "") : title }
}

extension NSImage {
    func pngData() -> Data? {
        guard let tiff = tiffRepresentation, let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }
}

// MARK: - Verlauf (beobachtet die Zwischenablage)

final class ClipStore {
    private(set) var items: [ClipItem] = []
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let fileURL: URL

    /// Maximale Anzahl Einträge (änderbar per `defaults write com.cheesycakeindustries.ClipStack maxItems 100`)
    var maxItems: Int {
        let v = UserDefaults.standard.integer(forKey: "maxItems")
        return v > 0 ? v : 50
    }

    /// Größere Bilder werden nicht gespeichert
    private let maxImageBytes = 8 * 1024 * 1024

    /// Typen, die Passwort-Manager setzen, um nicht protokolliert zu werden
    private let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init() {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        let dir = support.appendingPathComponent("ClipStack", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        fileURL = dir.appendingPathComponent("history.json")
        load()
    }

    func start() {
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount

        let types = pb.types ?? []
        if types.contains(where: { ignoredTypes.contains($0.rawValue) }) { return }

        if let urls = pb.readObjects(forClasses: [NSURL.self],
                                     options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            add(ClipItem(kind: .files, filePaths: urls.map { $0.path }, date: Date()))
        } else if let s = pb.string(forType: .string),
                  !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            add(ClipItem(kind: .text, text: s, rtf: pb.data(forType: .rtf), date: Date()))
        } else if let img = NSImage(pasteboard: pb), let png = img.pngData(), png.count <= maxImageBytes {
            add(ClipItem(kind: .image, imageData: png, date: Date()))
        }
    }

    private func add(_ item: ClipItem) {
        items.removeAll { $0.sameContent(as: item) }
        items.insert(item, at: 0)
        if items.count > maxItems { items.removeLast(items.count - maxItems) }
        save()
    }

    /// Legt einen Eintrag wieder in die Zwischenablage und schiebt ihn im Verlauf nach oben.
    func write(_ item: ClipItem) {
        let pb = NSPasteboard.general
        switch item.kind {
        case .text:
            var types: [NSPasteboard.PasteboardType] = [.string]
            if item.rtf != nil { types.insert(.rtf, at: 0) }
            pb.declareTypes(types, owner: nil)
            if let rtf = item.rtf { pb.setData(rtf, forType: .rtf) }
            pb.setString(item.text ?? "", forType: .string)
        case .image:
            pb.declareTypes([.png, .tiff], owner: nil)
            if let d = item.imageData {
                pb.setData(d, forType: .png)
                if let tiff = NSImage(data: d)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
            }
        case .files:
            pb.clearContents()
            let urls = (item.filePaths ?? []).map { NSURL(fileURLWithPath: $0) }
            pb.writeObjects(urls)
        }
        lastChangeCount = pb.changeCount
        var moved = item
        moved.date = Date()
        add(moved)
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.sameContent(as: item) }
        save()
    }

    func clear() {
        items.removeAll()
        save()
    }

    private func load() {
        guard let data = try? Data(contentsOf: fileURL),
              let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = decoded
    }

    private func save() {
        let snapshot = items
        let url = fileURL
        DispatchQueue.global(qos: .utility).async {
            if let data = try? JSONEncoder().encode(snapshot) {
                try? data.write(to: url, options: .atomic)
            }
        }
    }
}

// MARK: - Globales Tastenkürzel (⇧⌘V)

final class HotKey {
    private var hotKeyRef: EventHotKeyRef?
    private var handlerRef: EventHandlerRef?
    private let action: () -> Void
    private(set) var registered = false

    init(keyCode: UInt32, modifiers: UInt32, action: @escaping () -> Void) {
        self.action = action

        var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard),
                                 eventKind: UInt32(kEventHotKeyPressed))
        let selfPtr = Unmanaged.passUnretained(self).toOpaque()
        InstallEventHandler(GetApplicationEventTarget(), { _, _, userData in
            guard let userData = userData else { return noErr }
            let hotKey = Unmanaged<HotKey>.fromOpaque(userData).takeUnretainedValue()
            DispatchQueue.main.async { hotKey.action() }
            return noErr
        }, 1, &spec, selfPtr, &handlerRef)

        let id = EventHotKeyID(signature: OSType(0x434C_5053), id: 1) // 'CLPS'
        let status = RegisterEventHotKey(keyCode, modifiers, id, GetApplicationEventTarget(), 0, &hotKeyRef)
        registered = (status == noErr)
    }

    deinit {
        if let r = hotKeyRef { UnregisterEventHotKey(r) }
        if let h = handlerRef { RemoveEventHandler(h) }
    }
}

// MARK: - Einfügen per simuliertem ⌘V

enum Paster {
    static func isTrusted(prompt: Bool) -> Bool {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        return AXIsProcessTrustedWithOptions([key: prompt] as CFDictionary)
    }

    static func sendCmdV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let v = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}

